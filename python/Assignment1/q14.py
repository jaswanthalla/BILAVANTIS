# 14. List Slicing Challenge
# numbers = [10, 20, 30, 40, 50, 60, 70, 80]
# Use slicing to display:
# * First four elements
# * Last four elements
# * Elements from index 2 to 5
# * Every alternate element
# * Alternate elements starting from index 1
# * The list in reverse

numbers = [10, 20, 30, 40, 50, 60, 70, 80]
# first four elements

print(numbers[0:4])
print(numbers[-4:])
print(numbers[2:6])
print(numbers[::2])
print(numbers[1::2])
print(numbers[::-1])
