# 6. Create a variable containing your full name.
# Display:
# * First character
# * Last character
# * First three characters
# * Last three characters
# * Name in reverse

name = "jaswanth"
f = name[0]
last = name[-1]
f3 = name[0:3]
l3 = name[-3:]
reverse = name[::-1]

print("first character of my name:", f)
print("last character of my name:", last)
print("first three characters of my name:", f3)
print("last three characters of my name:", l3)
print("Name in reverse:", reverse)
